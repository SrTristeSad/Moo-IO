package.path="./?.lua;./?/init.lua;"..package.path
local Mobile=require("src.mobile.controls")
local function eq(a,b)assert(a==b,tostring(a).." ~= "..tostring(b))end
local m=Mobile.new()
local w,h=1280,720
local l=m:layout(w,h)
eq(m:attacking(),false)
eq(m:pressed(1,130,590,w,h),"move")
m:moved(1,190,590,w,h)
local dx,dy=m:movement()
assert(dx>.9 and math.abs(dy)<.001,"movement should point right")
eq(m:pressed(2,800,430,w,h),"aim")
m:moved(2,900,430,w,h)
assert(math.abs(m:aimAngle())<.0001,"right swipe should aim right")
eq(m:pressed(3,l.fire.x,l.fire.y,w,h),"attack")
eq(m:attacking(),true)
eq(m:released(3),"attack")
eq(m:attacking(),false)
eq(m:pressed(4,l.auto.x,l.auto.y,w,h),"attack")
eq(m:attacking(),true)
eq(m:pressed(5,l.auto.x,l.auto.y,w,h),"attack")
eq(m:attacking(),false)
eq(m:released(1),"move")
dx,dy=m:movement();eq(dx,0);eq(dy,0)
m:released(2)
eq(m:pressed(6,l.run.x,l.run.y,w,h),"run")
dx,dy=m:movement()
assert(dx>.9 and math.abs(dy)<.001,"autorun follows the last chosen direction")
eq(m:pressed(7,l.run.x,l.run.y,w,h),"run")
eq(m:pressed(8,l.minimap.x+10,l.minimap.y+10,w,h),"map_open")
local big=m:layout(w,h).bigmap
local action,where=m:pressed(9,big.x+big.w*.25,big.y+big.h*.75,w,h,14400)
eq(action,"ping");eq(where.x,3600);eq(where.y,10800)
eq(m.mapOpen,false)
eq(m:pressed(10,l.chat.x,l.chat.y,w,h),"chat_open")
assert(m.chatOpen)
local box=m:layout(w,h).modal
local x=box.x+box.w*.25
local y=box.y+65*l.u
action,where=m:pressed(11,x,y,w,h)
eq(action,"chat_select");eq(where,Mobile.messages[1])
eq(m:pressed(12,l.bag.x,l.bag.y,w,h),"bag_open")
eq(m.bagOpen,true)
eq(m:pressed(13,l.close.x,l.close.y,w,h),"bag_close")
eq(m:pressed(14,l.build.x,l.build.y,w,h),"build")
eq(m:pressed(15,l.swap.x,l.swap.y,w,h),"swap")
eq(m:pressed(16,l.gather.x,l.gather.y,w,h),"interact")
m:reset()
eq(m:attacking(),false)
eq(m.run,false)
print("MOO IO ANDROID TOUCH PASS")

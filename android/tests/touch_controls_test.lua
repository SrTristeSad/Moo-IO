package.path="./?.lua;./?/init.lua;"..package.path
local Mobile=require("src.mobile.controls")
local function eq(a,b)assert(a==b,tostring(a).." ~= "..tostring(b))end
local m=Mobile.new()
local w,h=1280,720
local l=m:layout(w,h)
eq(#l.skills,4)
eq(m:attacking(),false)
eq(m:pressed(1,l.move.x,l.move.y,w,h),"move")
m:moved(1,l.move.x+55,l.move.y,w,h)
local dx,dy=m:movement()
assert(dx>.9 and math.abs(dy)<.001,"movement should point right")
eq(m:pressed(2,800,430,w,h),"aim")
m:moved(2,900,430,w,h)
assert(math.abs(m:aimAngle())<.0001,"right swipe should aim right")
eq(m:pressed(3,l.fire.x,l.fire.y,w,h),"attack")
eq(m:attacking(),true)
eq(m:released(3),"attack")
eq(m:attacking(),false)
local action,on=m:pressed(4,l.auto.x,l.auto.y,w,h)
eq(action,"server_auto");eq(on,true)
eq(m:attacking(),false) -- E toggles server auto-gather, not held mouse F.
action,on=m:pressed(5,l.auto.x,l.auto.y,w,h)
eq(action,"server_auto");eq(on,false)
eq(m:released(1),"move")
dx,dy=m:movement();eq(dx,0);eq(dy,0)
m:released(2)
eq(m:pressed(6,l.run.x,l.run.y,w,h),"run")
dx,dy=m:movement()
assert(dx>.9 and math.abs(dy)<.001,"autorun should preserve last direction")
eq(m:pressed(7,l.run.x,l.run.y,w,h),"run")
for i,button in ipairs(l.skills) do
  local code,slot=m:pressed(20+i,button.x,button.y,w,h)
  eq(code,"skill");eq(slot,i)
end
eq(m:pressed(31,l.ping.x,l.ping.y,w,h),"ping_here")
eq(m:pressed(32,l.mark.x,l.mark.y,w,h),"map_open")
local big=m:layout(w,h).bigmap
local kind,where=m:pressed(33,big.x+big.w*.25,big.y+big.h*.75,w,h,14400)
eq(kind,"ping");eq(where.x,3600);eq(where.y,10800)
eq(m.mapOpen,false)
eq(m:pressed(34,l.rank.x,l.rank.y,w,h),"rank_open")
local b=l.rankPanel
local tabWidth=(b.w-24*l.u)/#Mobile.categories
kind,where=m:pressed(35,b.x+12*l.u+tabWidth*2.5,b.y+70*l.u,w,h)
eq(kind,"rank_category");eq(where,"food")
eq(m.rankingCategory,"food")
eq(m:pressed(36,l.close.x,l.close.y,w,h),"rank_close")
eq(m:pressed(37,l.chat.x,l.chat.y,w,h),"chat_open")
local box=m:layout(w,h).modal
kind,where=m:pressed(38,box.x+box.w*.25,box.y+65*l.u,w,h)
eq(kind,"chat_select");eq(where,Mobile.messages[1])
eq(m:pressed(39,l.bag.x,l.bag.y,w,h),"bag_open")
eq(m:pressed(40,l.close.x,l.close.y,w,h),"bag_close")
eq(m:pressed(41,l.build.x,l.build.y,w,h),"build")
eq(m:pressed(42,l.swap.x,l.swap.y,w,h),"swap")
eq(m:pressed(43,l.gather.x,l.gather.y,w,h),"interact")
m:reset()
eq(m:attacking(),false)
eq(m.auto,false);eq(m.run,false)
print("MOO IO ANDROID MOBA TOUCH PASS")

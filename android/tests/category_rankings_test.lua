local World=require("src.game.world_state")
local world=World.new()
assert(world:apply("n",{"gold",{8,"player A",920,10,"player B",500}}))
assert(#world.categoryRankings.gold==2)
assert(world.categoryRankings.gold[1].score==920)
assert(world:apply("n",{"food",{7,"collector",60}}))
assert(#world.categoryRankings.food==1)
assert(#world.categoryRankings.gold==2,"category data must remain independent")
assert(not world:apply("n",{"password",{7,"hacker",5}}))
assert(not world:apply("n",{"health",{7,"hacker",0/0}}))
assert(not world:apply("n",{"health",{7,{},22}}))
assert(not world:apply("n",{"health",{7,"bad",-12}}))
assert(not world:apply("n",{"health",{7,"bad",5,8}}))
assert(world.categoryRankings.health==nil,"invalid frames cannot override scoreboard")
